"""Choose the round Drag & Drop pieces for every story and level.

Reads the things marked in src/lib/story-items.ts and writes
src/lib/dragdrop-pieces.ts. Each level has its own piece count and size
(see LEVELS, and PIECE_RADIUS in src/lib/dragdrop.ts). Pieces are centred on
the marked things first, in order, skipping any that would overlap; if a
painting needs more, the rest go where the painting has the most detail
(edges and color), so no piece is plain sky.

  pip install opencv-python-headless numpy
  python scripts/make-dragdrop.py
"""
import json
import math
import os
import re

import cv2
import numpy as np

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
ASSETS = os.path.join(ROOT, "src", "assets")
RATIO = 1152 / 896  # painting height / width

# (pieces, radius in % of the painting width), Easy to Master.
LEVELS = [(3, 11), (5, 10), (7, 9), (9, 8), (11, 7)]
GAP = 1.5  # minimum space between two pieces, % of width


def load_items():
    src = open(os.path.join(ROOT, "src", "lib", "story-items.ts"), encoding="utf-8").read()
    body = src[src.index("= {") + 2 : src.rindex("};") + 1]
    body = re.sub(r",\s*}", "}", body)
    return json.loads(body)


def detail_map(slug):
    img = cv2.imread(os.path.join(ASSETS, f"puzzle-{slug}.jpg"))
    img = cv2.resize(img, (200, 257), interpolation=cv2.INTER_AREA)
    gray = cv2.cvtColor(img, cv2.COLOR_BGR2GRAY).astype(np.float32)
    edges = np.hypot(cv2.Sobel(gray, cv2.CV_32F, 1, 0), cv2.Sobel(gray, cv2.CV_32F, 0, 1))
    sat = cv2.cvtColor(img, cv2.COLOR_BGR2HSV)[..., 1].astype(np.float32)
    score = edges / (edges.max() + 1e-6) + 0.35 * sat / 255
    return cv2.GaussianBlur(score, (0, 0), 6)


def clamp(x, y, r):
    ry = r / RATIO
    return min(max(x, r), 100 - r), min(max(y, ry), 100 - ry)


def fits(x, y, r, chosen):
    return all(math.hypot(x - a, (y - b) * RATIO) >= 2 * r + GAP for a, b in chosen)


def pieces_for(slug, items, detail, count, r):
    chosen = []
    for _, x, y, _ in items:
        x, y = clamp(x, y, r)
        if fits(x, y, r, chosen):
            chosen.append((x, y))
        if len(chosen) == count:
            return chosen
    h, w = detail.shape
    cands = []
    for y in np.arange(r / RATIO, 100 - r / RATIO + 0.01, 2.0):
        for x in np.arange(r, 100 - r + 0.01, 2.0):
            cands.append((detail[int(y / 100 * (h - 1)), int(x / 100 * (w - 1))], x, y))
    cands.sort(reverse=True)
    for _, x, y in cands:
        if fits(x, y, r, chosen):
            chosen.append((float(x), float(y)))
            if len(chosen) == count:
                break
    return chosen


def main():
    items = load_items()
    out = [
        "// Generated by scripts/make-dragdrop.py from story-items.ts. Do not edit by",
        "// hand: run the script again after adding or changing stories.",
        "// Per story, one list of piece centres [x, y] (% of the painting) per level,",
        "// Easy to Master.",
        "export const DD_PIECES: Record<string, [number, number][][]> = {",
    ]
    for slug, its in items.items():
        detail = detail_map(slug)
        levels = []
        for count, r in LEVELS:
            ps = pieces_for(slug, its, detail, count, r)
            assert len(ps) == count, (slug, count, len(ps))
            levels.append([[round(x, 1), round(y, 1)] for x, y in ps])
        out.append(f"  {json.dumps(slug)}: {json.dumps(levels, separators=(',', ':'))},")
    out.append("};")
    open(os.path.join(ROOT, "src", "lib", "dragdrop-pieces.ts"), "w").write("\n".join(out) + "\n")
    print(f"{len(items)} stories")


if __name__ == "__main__":
    main()
