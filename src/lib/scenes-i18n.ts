export function localizeSceneTitle(slug: string, lang: Lang): string {
  return SCENE_TITLES[lang]?.[slug] ?? SCENE_TITLES.en[slug] ?? slug;
}

export function localizeVerse(verse: string, lang: Lang): string {
  const m = verse.match(/^(.+?)\s+(\d+:\d+)$/);
  if (!m) return verse;
  const bookEn = m[1];
  const ref = m[2];
  const localized = BOOKS[lang]?.[bookEn] ?? BOOKS.en[bookEn] ?? bookEn;
  return `${localized} ${ref}`;
}
