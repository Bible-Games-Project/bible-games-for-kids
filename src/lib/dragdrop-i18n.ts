export const DD_STRINGS: Record<Lang, Dict> = {
  en, es, de, fr, it, pt, pl, ru, ja, ko, ar, tr,
};

// Look up a dd.* key, falling back to English, then to the core dictionary
// (so shared keys like premium.* still resolve), then the raw key.
export function ddText(lang: Lang, key: string): string {
  return (
    DD_STRINGS[lang]?.[key] ??
    DD_STRINGS.en[key] ??
    CORE[lang]?.[key] ??
    CORE.en[key] ??
    key
  );
}
