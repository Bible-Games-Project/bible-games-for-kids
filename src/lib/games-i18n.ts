export const GAME_STRINGS: Record<Lang, Dict> = {
  en, es, de, fr, it, pt, pl, ru, ja, ko, ar, tr,
};

// Look up a game key, falling back to English, then to the core dictionary
// (so shared keys like diff.* still resolve), then the raw key. `{name}`
// placeholders are filled from `vars`.
export function gameText(lang: Lang, key: string, vars?: Record<string, string | number>): string {
  let text =
    GAME_STRINGS[lang]?.[key] ?? GAME_STRINGS.en[key] ?? CORE[lang]?.[key] ?? CORE.en[key] ?? key;
  for (const [k, v] of Object.entries(vars ?? {})) text = text.replace(`{${k}}`, String(v));
  return text;
}
